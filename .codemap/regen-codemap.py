#!/usr/bin/env python3
"""Rebuild the .codemap for this repo: module-graph.json, reverse-imports.json,
symbols.json, purposes.json, INDEX.md.

Usage: python3 .codemap/regen-codemap.py [repo-root]
"""
import json, re, os, sys

root = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
codemap = os.path.join(root, ".codemap")
os.makedirs(codemap, exist_ok=True)

pkg_path = os.path.join(root, "package.json")
pkg = json.load(open(pkg_path)) if os.path.exists(pkg_path) else {}
deps = {**pkg.get("dependencies", {}), **pkg.get("devDependencies", {})}

files = []
for dirpath, dirnames, filenames in os.walk(root):
    dirnames[:] = [d for d in dirnames if d not in ("node_modules", ".git", ".grok", ".codemap", "public", "dist", "build")]
    for f in filenames:
        if f.endswith((".ts", ".tsx", ".mjs", ".js", ".css", ".py")) and f not in ("package-lock.json", "routeTree.gen.ts"):
            if "__pycache__" in dirpath or dirpath.endswith("data"):
                continue
            files.append(os.path.join(dirpath, f))
files.sort()

imp_re = re.compile(r"""^\s*(?:import|export)\s+(?:[^'"]*?from\s+)?['"]([^'"]+)['"]""", re.M)
py_imp_re = re.compile(r"""^\s*(?:from\s+([.\w]+)\s+import|import\s+([.\w]+))""", re.M)
graph = {}
for fp in files:
    rel = os.path.relpath(fp, root)
    try:
        text = open(fp, encoding="utf8", errors="replace").read()
    except Exception:
        continue
    imps = set(imp_re.findall(text))
    for m in py_imp_re.finditer(text):
        imps.add(m.group(1) or m.group(2))
    graph[rel] = {"imports": sorted(imps), "loc": text.count("\n") + 1}

exp_re = re.compile(r"^\s*export\s+(?:async\s+)?(function|class|const|let|var|type|interface|enum)\s+([A-Za-z0-9_$]+)", re.M)
exports = {}
for fp in files:
    rel = os.path.relpath(fp, root)
    try:
        text = open(fp, encoding="utf8", errors="replace").read()
    except Exception:
        continue
    ex = sorted(set(m[1] for m in exp_re.findall(text)))
    if ex:
        exports[rel] = ex
json.dump({"files": files, "imports": graph, "exports": exports, "package_deps": deps},
          open(os.path.join(codemap, "module-graph.json"), "w"), indent=1)

reverse = {}
for rel, info in graph.items():
    for imp in info["imports"]:
        reverse.setdefault(imp, []).append(rel)
json.dump(reverse, open(os.path.join(codemap, "reverse-imports.json"), "w"), indent=1)

fn_re = re.compile(
    r"^\s*(?:export\s+(?:default\s+)?)?(?:async\s+)?function\s+([A-Za-z0-9_$]+)\s*\(([^)]*)\)"
    r"|^\s*(?:export\s+)?(?:const|let|var)\s+([A-Za-z0-9_$]+)\s*=\s*(?:async\s*)?(?:\([^)]*\)|[A-Za-z0-9_$]+)\s*(?::\s*[^=]+)?=>\s*"
    r"|^\s*class\s+([A-Za-z0-9_$]+)(?:\s+extends\s+([A-Za-z0-9_$\.\[\]<>\"']+))?"
    r"|^\s*export\s+(?:interface|type)\s+([A-Za-z0-9_$]+)", re.M)
symbols = {}
for fp in files:
    rel = os.path.relpath(fp, root)
    try:
        text = open(fp, encoding="utf8", errors="replace").read()
    except Exception:
        continue
    out = []
    for i, line in enumerate(text.splitlines(), 1):
        m = fn_re.match(line)
        if not m:
            pm = re.match(r"\s*(?:async\s+)?def\s+([A-Za-z_]\w*)\s*\(([^)]*)\)", line)
            if pm:
                indent = len(line) - len(line.lstrip())
                if indent == 0:
                    out.append(f"L{i}: fn {pm.group(1)}({pm.group(2).strip()[:60]})")
                else:
                    out.append(f"L{i}: m {pm.group(1)}({pm.group(2).strip()[:60]})")
                continue
            cm = re.match(r"\s*class\s+([A-Za-z_]\w*)", line)
            if cm and (len(line) - len(line.lstrip())) == 0:
                out.append(f"L{i}: class {cm.group(1)}")
                continue
            continue
        p = m.groups()
        if p[0]:
            out.append(f"L{i}: fn {p[0]}({p[1].strip()[:60]})")
        elif p[2]:
            out.append(f"L{i}: {p[2]} (arrow)")
        elif p[3]:
            out.append(f"L{i}: class {p[3]}" + (f" extends {p[4]}" if p[4] else ""))
        elif p[5]:
            out.append(f"L{i}: type {p[5]}")
    if out:
        symbols[rel] = out
json.dump(symbols, open(os.path.join(codemap, "symbols.json"), "w"), indent=1)

purpose = {}
for fp in files:
    rel = os.path.relpath(fp, root)
    text = open(fp, encoding="utf8", errors="replace").read()[:3000]
    m = re.search(r"/\*\*?(.*?)\*/", text, re.S)
    if not m:
        m = re.search(r'^(?:""\'\'\'|"""|\'\'\')(.*?)(?:"""|\'\'\'|""\'\')', text, re.S | re.M)
    if m and len(m.group(1).strip()) > 15:
        purpose[rel] = " ".join(m.group(1).split())[:200]
json.dump(purpose, open(os.path.join(codemap, "purposes.json"), "w"), indent=1)

lines = []
for rel in sorted(graph, key=lambda r: -graph[r]["loc"]):
    lines.append(f"{graph[rel]['loc']:5d} loc | {rel} | {len(symbols.get(rel, []))} syms | {purpose.get(rel, '')}")
open(os.path.join(codemap, "INDEX.md"), "w").write(
    "# Code map index\n\nAuto-generated by regen-codemap.py. "
    "Query module-graph.json / symbols.json with jq before opening source files.\n\n" + "\n".join(lines) + "\n")
print(f"codemap rebuilt: {len(files)} files, {sum(v['loc'] for v in graph.values())} loc")
